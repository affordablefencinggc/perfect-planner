import { createHash } from "node:crypto";
import { lstat, readFile, readdir } from "node:fs/promises";
import path from "node:path";

const defaultIgnored = new Set([".git", "node_modules", "dist", "target", "target-codex", "gen", "autogenerated", ".cache", ".local-preview-cache", ".ledger", "patches", ".turbo", "coverage", "generated"]);
const defaultExtensions = new Set([".md", ".txt", ".json", ".yaml", ".yml", ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".css", ".html", ".rs", ".toml", ".lock"]);

function slash(value) { return value.split(path.sep).join("/"); }
function sha256(bytes) { return createHash("sha256").update(bytes).digest("hex"); }

function categoryFor(relativePath, extension) {
  const lower = relativePath.toLowerCase();
  if (lower === ".githooks/pre-commit" || lower === ".githooks/pre-push") return "configuration";
  if (/(^|\/)tests?\//.test(lower) || /\.test\.[^.]+$/.test(lower)) return "test";
  if (extension === ".md" || extension === ".txt") return "document";
  if ([".json", ".yaml", ".yml"].includes(extension)) return "configuration";
  if ([".css", ".html"].includes(extension)) return "interface";
  return "source";
}

async function inspectFile(root, absolutePath, stats, maxBytes) {
  const relativePath = slash(path.relative(root, absolutePath));
  const extension = path.extname(relativePath).toLowerCase();
  if (stats.size > maxBytes) return { skipped: { path: relativePath, reason: `over ${maxBytes} byte limit`, size: stats.size } };
  const bytes = await readFile(absolutePath);
  const file = { path: relativePath, extension, category: categoryFor(relativePath, extension), size: stats.size, sha256: sha256(bytes) };
  if (extension === ".json") {
    try {
      const parsed = JSON.parse(bytes.toString("utf8"));
      if (parsed && typeof parsed === "object" && parsed.schemaVersion && parsed.planId && Array.isArray(parsed.tasks)) {
        file.category = "plan";
        file.planId = String(parsed.planId);
        file.taskCount = parsed.tasks.length;
      }
    } catch {
      file.parseWarning = "invalid JSON";
    }
  }
  return { file };
}

export async function censusRepository(rootPath, options = {}) {
  const root = path.resolve(rootPath);
  const maxFiles = Number(options.maxFiles ?? 10000);
  const maxBytes = Number(options.maxBytes ?? 2_000_000);
  const ignored = new Set([...(options.ignored ?? defaultIgnored)]);
  const extensions = new Set(options.extensions ?? defaultExtensions);
  const files = [];
  const skipped = [];
  const queue = [root];

  while (queue.length) {
    const directory = queue.shift();
    const entries = await readdir(directory, { withFileTypes: true });
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const entry of entries) {
      if (ignored.has(entry.name)) continue;
      const absolutePath = path.join(directory, entry.name);
      const relativePath = slash(path.relative(root, absolutePath));
      const stats = await lstat(absolutePath);
      if (stats.isSymbolicLink()) { skipped.push({ path: relativePath, reason: "symbolic link refused" }); continue; }
      if (stats.isDirectory()) { queue.push(absolutePath); continue; }
      const isDeliveryHook = relativePath === ".githooks/pre-commit" || relativePath === ".githooks/pre-push";
      if (!stats.isFile() || (!isDeliveryHook && !extensions.has(path.extname(entry.name).toLowerCase()))) continue;
      if (files.length >= maxFiles) throw new Error(`Repository census exceeded ${maxFiles} readable files.`);
      const result = await inspectFile(root, absolutePath, stats, maxBytes);
      if (result.file) files.push(result.file);
      if (result.skipped) skipped.push(result.skipped);
    }
  }

  files.sort((a, b) => a.path.localeCompare(b.path));
  const summary = files.reduce((counts, file) => {
    counts[file.category] = (counts[file.category] ?? 0) + 1;
    return counts;
  }, {});
  return {
    schemaVersion: 1,
    root,
    generatedAt: options.generatedAt ?? new Date().toISOString(),
    fileCount: files.length,
    summary,
    files,
    skipped,
    digest: sha256(Buffer.from(files.map((file) => `${file.path}:${file.sha256}`).join("\n"))),
  };
}
