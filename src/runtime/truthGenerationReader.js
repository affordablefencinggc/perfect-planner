const POINTER_URL = "/generated/current-generation.json";
const TRUTH_ARTIFACT_NAME = "truth-core-report.json";
const EXPECTED_ARTIFACT_NAMES = Object.freeze([
  TRUTH_ARTIFACT_NAME,
  "completion-report.json",
  "completion-report.md",
  "evidence-bundle.html",
]);
const SHA256_PATTERN = /^[a-f0-9]{64}$/;
const SAFE_DIRECTORY_PATTERN = /^generations\/[a-f0-9]{64}$/;

const SHIPPED_BUILD = import.meta.env?.PROD === true;

export const DEFAULT_TRUTH_READER_LIMITS = Object.freeze({
  maxPointerBytes: 32 * 1024,
  maxArtifactBytes: 2 * 1024 * 1024,
  // Dev regenerates truth continuously, so a day-old pointer there means a stale report. A production
  // bundle ships its truth generation inside the same build output (generated by the release build for
  // that exact revision), so wall-clock age is no freshness signal and a shipped release never expires.
  maxPointerAgeMs: SHIPPED_BUILD ? null : 24 * 60 * 60 * 1000,
  // Likewise a viewer's clock running behind the build machine must not invalidate a shipped release.
  maxFutureSkewMs: SHIPPED_BUILD ? null : 5 * 60 * 1000,
});

